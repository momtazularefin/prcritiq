"""File-level guardrails that keep PRCritiq quiet on noisy or unsafe input.

FR4 requires every skipped file to carry an explicit reason. The checks run in a
fixed precedence so the reported reason is the most informative one available:
safety first, then what the file *is*, then whether it is a language v1 reviews,
and only then how big it is. A huge lockfile is reported as a lockfile, not as an
oversized diff, because the former tells a reader why PRCritiq will never review
it while the latter suggests raising a budget would help.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from enum import StrEnum
from pathlib import PurePosixPath
from typing import Final

from .config import Settings
from .diff import SUPPORTED_LANGUAGES, FileDiff


class GuardrailDecision(StrEnum):
    """Structured guardrail verdicts, per the design Diff Plane."""

    REVIEWABLE = "reviewable"
    SKIPPED_GENERATED = "skipped_generated"
    SKIPPED_LOCKFILE = "skipped_lockfile"
    SKIPPED_VENDOR = "skipped_vendor"
    SKIPPED_BINARY = "skipped_binary"
    SKIPPED_OVERSIZED_FILE = "skipped_oversized_file"
    SKIPPED_OVERSIZED_DIFF = "skipped_oversized_diff"
    SKIPPED_UNSUPPORTED_LANGUAGE = "skipped_unsupported_language"
    SKIPPED_UNSAFE_PATH = "skipped_unsafe_path"


