# Deliberately specific. A bare "DO NOT EDIT" appears in ordinary prose and in
# test fixtures, so only conventional generator banners count here.
_GENERATED_MARKER: Final = re.compile(
    r"@generated\b|code generated by|do not edit this file|"
    r"automatically generated by|autogenerated by",
    re.IGNORECASE,
)

