class TestSizeBudgets:
    def test_oversized_patch_bytes_are_skipped(self) -> None:
        settings = Settings(max_file_bytes=200)
        big = "@@ -1,1 +1,101 @@\n alpha\n" + "+padding\n" * 100

        outcome = evaluate_file(diff_for("src/app.py", patch=big, changes=100), settings)

        assert outcome.decision is GuardrailDecision.SKIPPED_OVERSIZED_FILE

    def test_oversized_change_count_is_skipped(self) -> None:
        settings = Settings(max_diff_lines=10)

        outcome = evaluate_file(diff_for("src/app.py", changes=999), settings)

        assert outcome.decision is GuardrailDecision.SKIPPED_OVERSIZED_DIFF

    def test_missing_patch_for_a_supported_file_is_an_oversized_diff(self) -> None:
        """GitHub omits the patch when a text diff is too large to serve."""

        outcome = decide("src/app.py", patch=None, changes=5000)

        assert outcome.decision is GuardrailDecision.SKIPPED_OVERSIZED_DIFF
        assert "no patch" in outcome.reason

    def test_identity_outranks_size(self) -> None:
        """A huge lockfile reads as a lockfile, not as a budget a reader could raise."""

        settings = Settings(max_diff_lines=10, max_file_bytes=50)

        outcome = evaluate_file(diff_for("uv.lock", changes=9999), settings)

        assert outcome.decision is GuardrailDecision.SKIPPED_LOCKFILE


class TestPullRequestBudget:
    def test_reviewable_files_beyond_the_budget_are_reported_not_dropped(self) -> None:
        settings = Settings(max_files=2)
        diffs = [diff_for(f"src/mod_{index}.py") for index in range(4)]

        outcomes = apply_guardrails(diffs, settings)

        assert [item.decision for item in outcomes] == [
            GuardrailDecision.REVIEWABLE,
            GuardrailDecision.REVIEWABLE,
            GuardrailDecision.SKIPPED_OVERSIZED_DIFF,
            GuardrailDecision.SKIPPED_OVERSIZED_DIFF,
        ]
        assert "2-reviewable-file budget" in outcomes[3].reason

    def test_skipped_files_do_not_consume_the_budget(self) -> None:
        settings = Settings(max_files=2)
        diffs = [
            diff_for("README.md"),
            diff_for("src/first.py"),
            diff_for("uv.lock"),
            diff_for("src/second.py"),
        ]

        outcomes = apply_guardrails(diffs, settings)

        assert outcomes[1].reviewable is True
        assert outcomes[3].reviewable is True

    def test_reviewable_files_selects_the_paired_diffs(self) -> None:
        diffs = [diff_for("src/app.py"), diff_for("README.md")]

        outcomes = apply_guardrails(diffs, SETTINGS)

        assert [item.path for item in reviewable_files(diffs, outcomes)] == ["src/app.py"]

    def test_mismatched_lengths_are_rejected(self) -> None:
        with pytest.raises(ValueError, match="same length"):
            reviewable_files([diff_for("src/app.py")], ())
