"""Tests for the file guardrail gate."""

from __future__ import annotations

import pytest

from prcritiq.config import Settings
from prcritiq.diff import FileDiff, build_file_diff
from prcritiq.guardrails import (
    GuardrailDecision,
    GuardrailOutcome,
    apply_guardrails,
    evaluate_file,
    reviewable_files,
)

SETTINGS = Settings(max_files=30, max_diff_lines=2000, max_file_bytes=250_000)


def diff_for(
    path: str,
    *,
    patch: str | None = "@@ -1,1 +1,2 @@\n alpha\n+beta\n",
    changes: int = 1,
    status: str = "modified",
) -> FileDiff:
    return build_file_diff(
        path=path,
        status=status,
        additions=changes,
        deletions=0,
        changes=changes,
        patch=patch,
    )


def decide(path: str, **kwargs: object) -> GuardrailOutcome:
    return evaluate_file(diff_for(path, **kwargs), SETTINGS)  # type: ignore[arg-type]


class TestReviewable:
    @pytest.mark.parametrize("path", ["src/app.py", "web/main.ts", "web/widget.jsx"])
    def test_supported_source_files_are_reviewable(self, path: str) -> None:
        assert decide(path).decision is GuardrailDecision.REVIEWABLE


class TestUnsafePaths:
    @pytest.mark.parametrize(
        "path",
        [
            "../outside/secrets.py",
            "/etc/passwd.py",
            "C:/Windows/system.py",
            "src\\windows\\style.py",
            ".git/config.py",
            "   ",
        ],
    )
    def test_unsafe_paths_are_skipped(self, path: str) -> None:
        assert decide(path).decision is GuardrailDecision.SKIPPED_UNSAFE_PATH

    def test_unsafe_path_outranks_every_other_check(self) -> None:
        """Safety is evaluated before the file is classified or measured."""

        outcome = decide("../node_modules/uv.lock")

        assert outcome.decision is GuardrailDecision.SKIPPED_UNSAFE_PATH


class TestFileIdentity:
    @pytest.mark.parametrize("path", ["assets/logo.png", "dist/app.wasm", "lib/native.so"])
    def test_binary_extensions_are_skipped(self, path: str) -> None:
        assert decide(path).decision is GuardrailDecision.SKIPPED_BINARY

    @pytest.mark.parametrize("path", ["uv.lock", "package-lock.json", "backend/go.sum"])
    def test_lockfiles_are_skipped(self, path: str) -> None:
        assert decide(path).decision is GuardrailDecision.SKIPPED_LOCKFILE

    @pytest.mark.parametrize(
        "path", ["node_modules/left-pad/index.js", "vendor/github.com/pkg/errors.py"]
    )
    def test_vendored_code_is_skipped(self, path: str) -> None:
        assert decide(path).decision is GuardrailDecision.SKIPPED_VENDOR

    @pytest.mark.parametrize("path", ["static/app.min.js", "api/service_pb2.py", "web/bundle.map"])
    def test_generated_filenames_are_skipped(self, path: str) -> None:
        assert decide(path).decision is GuardrailDecision.SKIPPED_GENERATED

    def test_generated_output_directories_are_skipped(self) -> None:
        assert decide("dist/bundle.js").decision is GuardrailDecision.SKIPPED_GENERATED

    def test_generator_banner_in_the_patch_is_skipped(self) -> None:
        patch = "@@ -1,1 +1,2 @@\n alpha\n+# Code generated by protoc. DO NOT EDIT.\n"

        assert decide("src/models.py", patch=patch).decision is GuardrailDecision.SKIPPED_GENERATED

    def test_ordinary_prose_does_not_trip_the_generator_banner(self) -> None:
        """A tight marker list keeps hand-written warnings reviewable."""

        patch = '@@ -1,1 +1,2 @@\n alpha\n+RULES = "DO NOT EDIT while the lock is held"\n'

        assert decide("src/models.py", patch=patch).decision is GuardrailDecision.REVIEWABLE

    def test_a_directory_named_like_output_does_not_skip_the_file_itself(self) -> None:
        """Only parent segments are matched, so a file named build.py stays reviewable."""

        assert decide("src/build.py").decision is GuardrailDecision.REVIEWABLE


